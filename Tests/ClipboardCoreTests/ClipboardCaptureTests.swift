/// A private pasteboard, so no test reads or changes the real clipboard.
final class ScratchPasteboard {
    let pasteboard = NSPasteboard(name: NSPasteboard.Name("quickshot-clip-test-\(UUID().uuidString)"))
    deinit { pasteboard.releaseGlobally() }

    func set(_ contents: [(NSPasteboard.PasteboardType, Data)]) {
        let item = NSPasteboardItem()
        for (type, data) in contents { item.setData(data, forType: type) }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
    }

    func setText(_ text: String, extra: [NSPasteboard.PasteboardType] = []) {
        set([(.string, Data(text.utf8))] + extra.map { ($0, Data()) })
    }
}

@MainActor
@Suite struct ClipboardReaderTests {
    @Test func plainTextIsReadWithItsSourceApp() {
        let scratch = ScratchPasteboard()
        scratch.setText("hello")
        #expect(ClipboardReader.read(scratch.pasteboard, sourceApp: "com.example.notes")
            == .item(.text("hello", sourceApp: "com.example.notes")))
    }

    /// The content of a marked copy must never be read. The pasteboard here
    /// holds a secret string; the outcome carries no text at all.
    @Test(arguments: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                      "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"])
    func markedCopiesAreSkippedBeforeTheirContentIsRead(marker: String) {
        let scratch = ScratchPasteboard()
        scratch.setText("hunter2", extra: [NSPasteboard.PasteboardType(marker)])
        #expect(ClipboardReader.read(scratch.pasteboard, sourceApp: nil) == .skipped(.secret))
    }

    @Test func copiesFromAnIgnoredAppAreSkipped() {
        let scratch = ScratchPasteboard()
        scratch.setText("a password")
        #expect(ClipboardReader.read(scratch.pasteboard, sourceApp: "com.apple.Passwords") == .skipped(.ignoredApp))
        #expect(ClipboardReader.read(scratch.pasteboard, sourceApp: "com.example.custom", ignoredApps: ["com.example.custom"])
            == .skipped(.ignoredApp))
    }

    @Test func quickShotsOwnWritesAreSkipped() {
        let scratch = ScratchPasteboard()
        scratch.setText("copied back", extra: [ClipboardReader.ownWriteType])
        #expect(ClipboardReader.read(scratch.pasteboard, sourceApp: nil) == .skipped(.ownWrite))
    }

    @Test func aPictureIsReadAsAnImageWithItsPixelSize() throws {
        let scratch = ScratchPasteboard()
        let png = makePNG(width: 120, height: 80)
        scratch.set([(.png, png)])

        guard case .item(let candidate) = ClipboardReader.read(scratch.pasteboard, sourceApp: "com.example.browser") else {
            Issue.record("expected an image")
            return
        }
        #expect(candidate.kind == .image)
        #expect(candidate.imageData == png)
        #expect(candidate.pixelWidth == 120 && candidate.pixelHeight == 80)
        #expect(candidate.sourceApp == "com.example.browser")
    }

    @Test func aTIFFPictureIsStoredAsPNG() throws {
        let scratch = ScratchPasteboard()
        let tiff = try #require(NSBitmapImageRep(data: makePNG(width: 20, height: 10))?.tiffRepresentation)
        scratch.set([(.tiff, tiff)])

        guard case .item(let candidate) = ClipboardReader.read(scratch.pasteboard, sourceApp: nil) else {
            Issue.record("expected an image")
            return
        }
        #expect(candidate.imageData?.prefix(4) == Data([0x89, 0x50, 0x4E, 0x47]))
        #expect(candidate.pixelWidth == 20)
    }

    /// A word processor copies text, rich text and a picture of the text.
    @Test func richTextWithARenderedPictureIsKeptAsText() {
        let scratch = ScratchPasteboard()
        scratch.set([(.string, Data("Quarterly plan".utf8)), (.rtf, Data("{\\rtf1 Quarterly plan}".utf8)), (.png, makePNG())])
        #expect(ClipboardReader.read(scratch.pasteboard, sourceApp: nil) == .item(.text("Quarterly plan")))
    }

    /// A browser's "Copy Image" carries the picture and its address as text.
    @Test func aPictureWithPlainTextBesideItIsKeptAsAnImage() {
        let scratch = ScratchPasteboard()
        scratch.set([(.string, Data("https://example.com/cat.png".utf8)), (.png, makePNG(width: 9, height: 9))])
        guard case .item(let candidate) = ClipboardReader.read(scratch.pasteboard, sourceApp: nil) else {
            Issue.record("expected an item")
            return
        }
        #expect(candidate.kind == .image)
    }

    @Test func copiedFilesAreReadAsPaths() throws {
        let folder = try TempFolder()
        let file = try folder.write(Fixture.png, named: "shot.png")
        let scratch = ScratchPasteboard()
        scratch.set([(.fileURL, Data(file.absoluteString.utf8)), (.string, Data("shot.png".utf8)), (.tiff, Data([1, 2, 3]))])

        guard case .item(let candidate) = ClipboardReader.read(scratch.pasteboard, sourceApp: nil) else {
            Issue.record("expected files")
            return
        }
        #expect(candidate.kind == .files)
        #expect(candidate.text == file.path)
    }

    @Test func anEmptyPasteboardGivesNothing() {
        let scratch = ScratchPasteboard()
        scratch.pasteboard.clearContents()
        #expect(ClipboardReader.read(scratch.pasteboard, sourceApp: nil) == .nothing)
    }
}

@MainActor
@Suite struct ClipboardMonitorTests {
    @MainActor
    final class Harness {
        let folder: TempFolder
        let store: ClipStore
        let scratch = ScratchPasteboard()
        var denied = false
        var frontmost: String? = "com.example.editor"
        var changes = 0
        private(set) var monitor: ClipboardMonitor!

        init() throws {
            folder = try TempFolder()
            store = try ClipStore(directory: folder.url)
            scratch.setText("on the clipboard before launch")
            monitor = ClipboardMonitor(
                pasteboard: scratch.pasteboard, store: store,
                frontmostApp: { [unowned self] in frontmost },
                accessDenied: { [unowned self] in denied },
                onChange: { [unowned self] in changes += 1 })
        }

        var texts: [String] { (try? store.items(in: .history).map(\.text)) ?? [] }
    }

    @Test func whatWasCopiedBeforeLaunchIsNotRecorded() throws {
        let harness = try Harness()
        harness.monitor.tick()
        #expect(harness.texts.isEmpty)
    }

    @Test func eachNewCopyIsRecordedOnce() throws {
        let harness = try Harness()

        harness.scratch.setText("one")
        harness.monitor.tick()
        harness.monitor.tick() // nothing changed: no second record
        harness.scratch.setText("two")
        harness.monitor.tick()

        #expect(harness.texts.count == 2)
        #expect(Set(harness.texts) == ["one", "two"])
        #expect(harness.changes == 2)
        #expect(try harness.store.items(in: .history).allSatisfy { $0.sourceApp == "com.example.editor" })
    }

    @Test func secretsAndIgnoredAppsNeverReachTheStore() throws {
        let harness = try Harness()

        harness.scratch.setText("hunter2", extra: [NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")])
        harness.monitor.tick()
        harness.frontmost = "com.apple.Passwords"
        harness.scratch.setText("another secret")
        harness.monitor.tick()

        #expect(harness.texts.isEmpty)
        #expect(harness.changes == 0)
    }

    @Test func copyingAnItemBackDoesNotCreateOrReorderItems() throws {
        let harness = try Harness()
        harness.scratch.setText("older")
        harness.monitor.tick()
        try harness.store.record(.text("newer"), at: Date().addingTimeInterval(10))
        let older = try #require(try harness.store.items(in: .history).last)

        #expect(ClipboardWriter.write(older, from: harness.store, to: harness.scratch.pasteboard))
        harness.monitor.tick()

        #expect(harness.scratch.pasteboard.string(forType: .string) == "older")
        #expect(harness.texts == ["newer", "older"], "copy-back must not move the item or add a duplicate")
    }

    @Test func pausedHistoryRecordsNothingAndDoesNotCatchUpLater() throws {
        let harness = try Harness()

        harness.monitor.isPaused = true
        #expect(harness.monitor.state == .paused)
        harness.scratch.setText("copied while paused")
        harness.monitor.tick()
        harness.monitor.isPaused = false
        harness.monitor.tick()
        #expect(harness.texts.isEmpty)

        harness.scratch.setText("after resuming")
        harness.monitor.tick()
        #expect(harness.texts == ["after resuming"])
    }

    @Test func aDeniedClipboardIsReportedAndNothingIsRead() throws {
        let harness = try Harness()

        harness.denied = true
        harness.scratch.setText("not allowed")
        harness.monitor.tick()
        #expect(harness.monitor.state == .blocked)
        #expect(harness.texts.isEmpty)

        harness.denied = false
        harness.monitor.tick()
        #expect(harness.monitor.state == .running)
        #expect(harness.texts == ["not allowed"], "once allowed, the copy still on the clipboard is recorded")
    }
}

@MainActor
@Suite struct ClipboardWriterAndExporterTests {
    @Test func writingAnImageBackPutsThePNGOnThePasteboardMarkedAsOwn() throws {
        let folder = try TempFolder()
        let store = try ClipStore(directory: folder.url)
        let candidate = imageCandidate(width: 30, height: 20)
        let item = try #require(try store.record(candidate))
        let scratch = ScratchPasteboard()

        #expect(ClipboardWriter.write(item, from: store, to: scratch.pasteboard))

        #expect(scratch.pasteboard.data(forType: .png) == candidate.imageData)
        #expect(scratch.pasteboard.types?.contains(ClipboardReader.ownWriteType) == true)
    }

    @Test func writingFilesBackPutsEveryFileOnThePasteboard() throws {
        let folder = try TempFolder()
        let store = try ClipStore(directory: folder.url.appendingPathComponent("store"))
        let a = try folder.write(Fixture.png, named: "a.png"), b = try folder.write(Fixture.png, named: "b.png")
        let item = try #require(try store.record(.files([a, b])))
        let scratch = ScratchPasteboard()

        #expect(ClipboardWriter.write(item, from: store, to: scratch.pasteboard))

        let urls = scratch.pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]
        #expect(urls?.map(\.lastPathComponent) == ["a.png", "b.png"])
        #expect(ClipboardReader.read(scratch.pasteboard, sourceApp: nil) == .skipped(.ownWrite))
    }

    @Test func exportWritesACopyAndLeavesTheItemInPlace() throws {
        let folder = try TempFolder()
        let store = try ClipStore(directory: folder.url.appendingPathComponent("store"))
        let text = try #require(try store.record(.text("line one\nline two")))
        let picture = imageCandidate()
        let image = try #require(try store.record(picture))
        let original = try folder.write(Fixture.mov, named: "clip.mov")
        let files = try #require(try store.record(.files([original])))
        let destination = folder.url.appendingPathComponent("Exports")
        let date = Date(timeIntervalSince1970: 1_800_000_000)

        let textOut = try ClipExporter.export(text, from: store, to: destination, date: date)
        let textAgain = try ClipExporter.export(text, from: store, to: destination, date: date)
        let imageOut = try ClipExporter.export(image, from: store, to: destination, date: date)
        let filesOut = try ClipExporter.export(files, from: store, to: destination, date: date)

        #expect(try String(contentsOf: textOut[0], encoding: .utf8) == "line one\nline two")
        #expect(textOut[0].lastPathComponent.hasPrefix("Clipboard Text ") && textOut[0].pathExtension == "txt")
        #expect(textAgain[0] != textOut[0], "a second export must not overwrite the first")
        #expect(try Data(contentsOf: imageOut[0]) == picture.imageData)
        #expect(filesOut.map(\.lastPathComponent) == ["clip.mov"])
        #expect(FileManager.default.fileExists(atPath: original.path), "export copies; the original stays")
        #expect(try store.items(in: .history).count == 3, "export leaves every item in history")
        #expect(FileManager.default.fileExists(atPath: try #require(store.imageURL(for: image)).path))
    }
}
