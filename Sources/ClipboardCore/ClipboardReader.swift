import AppKit

/// Turns what is on a pasteboard into one item of history, or says why not.
///
/// Every check that can skip a copy runs on the list of type names only, so a
/// secret's content is never read.
public enum ClipboardReader {
    public enum SkipReason: Sendable, Equatable {
        /// Marked confidential, short-lived or machine-made by the app that copied it.
        case secret
        /// Written by QuickShot itself (copy-back, or copying a capture).
        case ownWrite
        /// Copied while an ignored app was in front.
        case ignoredApp
    }

    public enum Outcome: Sendable, Equatable {
        case item(ClipCandidate)
        case skipped(SkipReason)
        /// Nothing this app keeps (an empty pasteboard or an unknown format).
        case nothing
    }

    /// Added to everything QuickShot writes, so its own copies are not recorded again.
    public static let ownWriteType = NSPasteboard.PasteboardType("ai.rosslabs.quickshot.own-write")

    /// Type names apps use to mark copies that history tools should not keep
    /// (the nspasteboard.org convention, plus 1Password's older marker).
    public static let markerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// Apps whose copies are never kept, by bundle identifier.
    public static let defaultIgnoredApps: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
    ]

    public static func read(
        _ pasteboard: NSPasteboard,
        sourceApp: String?,
        ignoredApps: Set<String> = defaultIgnoredApps
    ) -> Outcome {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        if types.contains(ownWriteType.rawValue) { return .skipped(.ownWrite) }
        if !types.isDisjoint(with: markerTypes) { return .skipped(.secret) }
        if let sourceApp, ignoredApps.contains(sourceApp) { return .skipped(.ignoredApp) }

        // Files first: Finder also puts an icon image and the name as text on the pasteboard.
        let fileURLs = (pasteboard.readObjects(
            forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        if !fileURLs.isEmpty { return .item(.files(fileURLs, sourceApp: sourceApp)) }

        // Rich text apps add a picture of the text beside it, so an image counts
        // only when the copy carries no rich text.
        let hasImage = types.contains(NSPasteboard.PasteboardType.png.rawValue)
            || types.contains(NSPasteboard.PasteboardType.tiff.rawValue)
        let hasRichText = types.contains(NSPasteboard.PasteboardType.rtf.rawValue)
            || types.contains(NSPasteboard.PasteboardType.html.rawValue)
        let text = pasteboard.string(forType: .string) ?? ""
        if hasImage, !hasRichText || text.isEmpty, let image = image(from: pasteboard) { return .item(image.with(sourceApp)) }
        if !text.isEmpty { return .item(.text(text, sourceApp: sourceApp)) }
        if hasImage, let image = image(from: pasteboard) { return .item(image.with(sourceApp)) }
        return .nothing
    }

    /// The pasteboard's image as PNG, with its pixel size.
    private static func image(from pasteboard: NSPasteboard) -> ClipCandidate? {
        guard let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
              let bitmap = NSBitmapImageRep(data: data),
              let png = pasteboard.data(forType: .png) ?? bitmap.representation(using: .png, properties: [:])
        else { return nil }
        return ClipCandidate(kind: .image, imageData: png, pixelWidth: bitmap.pixelsWide, pixelHeight: bitmap.pixelsHigh)
    }
}

private extension ClipCandidate {
    func with(_ sourceApp: String?) -> ClipCandidate {
        var copy = self
        copy.sourceApp = sourceApp
        return copy
    }
}

/// Puts a stored item back on a pasteboard, marked as QuickShot's own write.
public enum ClipboardWriter {
    @discardableResult
    public static func write(_ item: ClipItem, from store: ClipStore, to pasteboard: NSPasteboard) -> Bool {
        var entries: [NSPasteboardItem] = []
        switch item.kind {
        case .text:
            let entry = NSPasteboardItem()
            entry.setString(item.text, forType: .string)
            entries = [entry]
        case .image:
            guard let url = store.imageURL(for: item), let data = try? Data(contentsOf: url) else { return false }
            let entry = NSPasteboardItem()
            entry.setData(data, forType: .png)
            entries = [entry]
        case .files:
            entries = item.filePaths.map { path in
                let entry = NSPasteboardItem()
                entry.setString(URL(fileURLWithPath: path).absoluteString, forType: .fileURL)
                return entry
            }
        }
        guard let first = entries.first else { return false }
        first.setData(Data(), forType: ClipboardReader.ownWriteType)
        pasteboard.clearContents()
        return pasteboard.writeObjects(entries)
    }
}
